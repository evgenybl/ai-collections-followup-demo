# A phrase in a customer's notes, and what a person should look at when it is there.
NOTE_FOR_A_PERSON = [
    ("never arrived", "says an invoice never arrived; a person should check that it was sent before any reminder."),
    ("Disputes", "disputes an invoice; a person should settle the dispute before any reminder goes out."),
    ("instalments", "asked to pay in instalments; a person must decide whether to accept, and on what terms."),
    ("Promised", "promised to pay by the end of the month; a person should check whether the promise is kept."),
    ("No answer", "does not answer the phone; a person should confirm the e-mail address before writing."),
]


def json_number(value):
    """A Decimal as a JSON number: an int when it is whole, else a float that reads back as the same Decimal."""
    if value == value.to_integral_value():
        return int(value)
    as_float = float(value)
    if Decimal(repr(as_float)) != value:
        raise ValueError(f"{value} does not survive the trip through a JSON number")
    return as_float


def written(value):
    """An amount as a person writes it in a letter: 14,770 or 34,256.40. The checks read both forms."""
    return f"{value:,.0f}" if value == value.to_integral_value() else f"{value:,.2f}"


def constructed_answer(prep):
    """A correct answer CONSTRUCTED from the sheet's own figures (not a model's): every owing customer of the request,
    in the order an ageing report is usually worked (the oldest bucket first, the larger total first inside a bucket,
    customers not late yet last); a reason and a reminder that state only the customer's own total and delay; and a
    note for a person for each owing customer whose notes need judgment."""
    oldest_first = {bucket: rank for rank, bucket in enumerate(reversed(pipeline.BUCKETS))}
    owing = sorted(((who, c) for who, c in prep["expected"].items() if c["total"] > 0),
                   key=lambda pair: (oldest_first[pipeline.bucket_of(pair[1])], -pair[1]["total"], pair[0]))
    call_list, for_a_human = [], []
    for priority, (who, c) in enumerate(owing, start=1):
        total, days = written(c["total"]), c["days"]
        if days:
            reason = f"A balance of {total}; the oldest open invoice is {days} days late."
            reminder = (f"Dear {who}, our records show an outstanding balance of {total}, now {days} days late. "
                        "Please arrange payment, or contact us if anything is unclear. Thank you.")
        else:
            reason = f"A balance of {total} that is not late yet."
            reminder = (f"Dear {who}, a friendly note that a balance of {total} is open on your account. "
                        "Please contact us if anything is unclear. Thank you.")
        call_list.append({"customer": who, "priority": priority, "amount": json_number(c["total"]),
                          "days_late": days, "reason": reason, "reminder": reminder})
        notes = " ".join(row[pipeline.NOTES] for row in prep["clean"] if row[pipeline.NAME] == who)
        for phrase, what in NOTE_FOR_A_PERSON:
            if phrase in notes:
                for_a_human.append(f"{who} {what}")
    return {"call_list": call_list, "for_a_human": for_a_human}


def constructed_answer_text(prep):
    """The constructed answer as the text of an answer file: JSON on one line, then a line end."""
    return json.dumps(constructed_answer(prep), ensure_ascii=False) + "\n"
